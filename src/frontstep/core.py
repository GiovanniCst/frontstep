def field_names(field: str) -> tuple[str, ...]:
    """Every name under which that field may appear in a document."""
    entry = FIELDS[field]
    return tuple(dict.fromkeys([entry["en"], entry["it"], *entry["alias"]]))


def field_name(field: str, language: str = "en") -> str:
    """The name that field is WRITTEN with, in the given language."""
    return FIELDS[field][language if language in LANGUAGES else "en"]


