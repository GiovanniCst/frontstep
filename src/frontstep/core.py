"""Reading the open fronts: scans the status documents of every project.

Nothing is persisted: the filesystem is read again on every request. These are a
few dozen files and a single page, so a cache would only be a way of showing
stale data.

The parser is deliberately tolerant: a status document without a header is not
an error, it is a project whose header still has to be written.

There is MORE THAN ONE root — the folders where someone keeps their projects —
and a project's name is unique within its root, not across roots: the root is
part of every project's address.
"""
