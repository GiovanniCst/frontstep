@dataclass(frozen=True)
class Root:
    """A folder that projects are scanned from.

    It is not just one more path: a project's name is unique within its root and
    not across roots, so the root is part of every project's address
    (`/project/<root>/<name>`). Two folders with the same name under two roots
    are two different projects, and "Close" has to write to the right file.

    It also carries the base TAGS of its projects: where a project sits says
    what kind of work it is, and the project's own document can add to that.
    """
    key: str        # in the URL and in the element ids on the page
    folder: str     # where projects are scanned from (inside the container, if any)
    host: str       # the same path on the host: this is what gets copied
    prefix: str     # how it reads on a card: "~/projects/" or "~/"
    label: str = ""             # what this folder is called, for whoever uses it
    tags: tuple[str, ...] = ()  # base tags, inherited by every project under it

    def __post_init__(self):
        if not self.label:
            object.__setattr__(self, "label", self.key)


@dataclass
class Project:
    name: str
    status: str
    title: str = ""
    description: str = ""         # from the Description field, or derived from the text
    description_derived: bool = False
    folder: str = ""              # folder name inside the root, "" if it has none
    root: str = ""                # key of the root it was found under
    prefix: str = ""              # the path as it reads on the card
    host_folder: str = ""         # the folder on the host, for the path tooltip
    # The tags: the root's plus the document's. The FIRST one is what the card
    # shows as a coloured band; the others are badges in the footer.
    tags: tuple[str, ...] = ()
    app_name: str = ""            # what the product is called, from the App field
    in_production: bool = False   # the Prod field is there and is not a negation
    prod_note: str = ""           # its value: usually the name of the service
    updated: dt.date | None = None
    next_step: str = ""
    waiting_for: str = ""
    status_file: str = ""         # HOST path, the one that gets copied
    status_filename: str = ""     # the file name as found on disk
    mtime: dt.date | None = None
    remote_url: str = ""          # the repository's origin remote, if it has one
    has_status_file: bool = False
    has_header: bool = False
    has_status: bool = False      # there is a status line that can be rewritten
    has_next_step: bool = False   # there is a next step line that can be rewritten
    canonical_casing: bool = True
    index_note: str = ""
    index_file: str = ""

    @property
    def status_label(self) -> str:
        """The status as a word to read, in English, ready for `t()`.

        Not the canonical value: `active` is what the document and the URL say,
        and it is a token, not a word anybody should be read out. The card shows
        the status as the colour of its paper, so the only place this surfaces is
        the line a screen reader gets — and that line used to announce "active"
        in the middle of a page otherwise entirely in Italian, because the raw
        status went straight into the markup.
        """
        return LABELS.get(self.status, self.status)

    @property
    def days_silent(self) -> int | None:
        """How many days this project has not moved.

        The `Updated` field is the declared date of the last real work and beats
        the mtime, which changes for a typo fix too.
        """
        reference = self.updated or self.mtime
        if reference is None:
            return None
        return (dt.date.today() - reference).days

    @property
    def header_behind(self) -> bool:
        """The file was touched after the date its header declares."""
        if not (self.updated and self.mtime):
            return False
        return (self.mtime - self.updated).days > 1

    @property
    def section_index(self) -> int:
        """Index of the section the card lands in, not of the status."""
        return _SECTION_OF_STATUS.get(self.status, len(SECTIONS))

    @property
    def ident(self) -> str:
        """Unique key on the page: the name alone is no longer enough.

        Two roots can hold two folders with the same name, and two equal ids
        would break the silence line — it would scroll to the wrong card —
        without telling anyone why.
        """
        return f"{self.root}:{self.name}" if self.root else self.name


def _normalize_status(raw: str) -> str:
    """Canonical status from a hand-written value. "" if not recognised.

    It copes with the qualifications an external index drags along:
    "paused 2026-04-23" → paused, "active, to run" → active.
    """
    text = (raw or "").strip().lower()
    if not text:
        return ""
    if text in STATUS_ALIASES:
        return STATUS_ALIASES[text]
    words = [w for w in re.split(r"[\s,;]+", text) if w]
    for n in (2, 1):                      # "on hold" before "on"
        candidate = " ".join(words[:n])
        if candidate in STATUS_ALIASES:
            return STATUS_ALIASES[candidate]
    return ""


def _field_regex(name: str) -> re.Pattern:
    return re.compile(RE_FIELD.format(field=re.escape(name)), re.IGNORECASE)


def _find_field(lines: list[str], field: str) -> tuple[int, str, str] | None:
    """(line number, name used, value) of the field's first occurrence, in any
    of the languages and aliases. None if it is not there.

    The FIRST one wins: long documents repeat "Updated" in the body, and that is
    not the header. Lines are scanned outer and names inner, otherwise an alias
    quoted at the bottom of a document would beat the real field written on top.

    ⚠️ Fenced blocks are skipped. A document that SHOWS the header format in a
    ``` block before writing its own had the example matched instead of the
    header — read from it, and written into it.
    """
    patterns = [(name, _field_regex(name)) for name in field_names(field)]
    inside_fence = False
    for i, line in enumerate(lines):
        if line.lstrip().startswith(("```", "~~~")):
            inside_fence = not inside_fence
            continue
        if inside_fence:
            continue
        for name, rx in patterns:
            m = rx.match(line)
            if m:
                return i, name, m.group(1).strip()
    return None


def _read_field(lines: list[str], field: str) -> str:
    """The field's value in the header, in whatever language it is written."""
    found = _find_field(lines, field)
    return found[2] if found else ""


def _has_field(lines: list[str], field: str) -> bool:
    """The field's LINE is there, even with an empty value.

    Not the same question as `_read_field(...) != ""`: a `**Status:**` with no
    value is a line that can be rewritten, and whether the "Close" button has
    anything to work on depends on it.
    """
    return _find_field(lines, field) is not None


def normalize_tag(raw: str) -> str:
    """A hand-written tag becomes a stable key: `Prod`, `prod` and `PROD` are
    the same tag. Without this, the same word spelled two ways would become two
    different filters on the page."""
    text = (raw or "").strip().strip("`*").lower()
    text = re.sub(r"[\s_]+", "-", text)
    text = re.sub(r"[^a-z0-9àáâäãåèéêëìíîïòóôöõùúûüñç.-]", "", text)
    return text.strip("-.")


# The historical names of the field that carries tags today. When a value comes
# from one of these it was an ENUM of a few entries, not a free tag: `PERSONALE`
# and `personal` were the same domain, and letting them become two different
# tags would be a regression for documents already written. The aliases apply
# HERE ONLY: whoever writes `Tags: personale` today means that tag, and keeps it.
LEGACY_DOMAIN_FIELDS = ("Domain", "Dominio", "Ambito")

LEGACY_TAG_ALIASES = {
    "personale": "personal", "privato": "personal", "private": "personal",
    "casa": "personal", "home": "personal",
    "lavoro": "work", "azienda": "work", "company": "work", "ufficio": "work",
}


def project_tags(lines: list[str], from_root: tuple[str, ...],
                 in_production: bool = False) -> tuple[str, ...]:
    """A project's tags: its root's, plus its document's own.

    Two levels, because they answer two different questions: the root says what
    that folder is (`work`), the document says what that project is (`prod`,
    `client-acme`). "In production" is a property of the single project, not of
    the folder holding it, and with one exclusive domain it was not expressible.

    An inherited tag can be REMOVED by writing it with a minus: `-work`. That
    serves the rare but real case of a project sitting in the wrong folder — a
    personal one among the work ones — and without it inheritance would be a cage.

    Order matters: the first tag is the one the card shows as its band, and it
    stays the root's until someone takes it away.
    """
    added: list[str] = []
    removed: set[str] = set()
    found = _find_field(lines, "tags")
    raw = found[2] if found else ""
    legacy = bool(found) and found[1] in LEGACY_DOMAIN_FIELDS

    def tag(piece: str) -> str:
        key = normalize_tag(piece)
        return LEGACY_TAG_ALIASES.get(key, key) if legacy else key

    for piece in re.split(r"[,;]", raw):
        piece = piece.strip()
        if not piece:
            continue
        if piece.startswith("-"):
            removed.add(tag(piece[1:]))
        else:
            added.append(tag(piece))
    if in_production:
        added.append(PROD_TAG)

    ordered = [t for t in from_root if t and t not in removed]
    ordered += [t for t in added if t and t not in removed]
    return tuple(dict.fromkeys(ordered))


def document_language(lines: list[str]) -> str:
    """Which language the header is written in: "it" or "en".

    This is needed when WRITING: a document that says `**Stato:** attivo` has to
    stay that way after a "Close", not turn into `**Status:** done`. It looks at
    how the field NAMES are written, not the values: the name is a choice made
    by whoever wrote the file, the value may have been put there by someone else.

    On a tie (or with no recognisable field) English wins, being the project's
    canonical language. Fields spelled the same in both languages — `App`,
    `Prod` — do not vote, and rightly so: they say nothing about the language.
    """
    votes = {"en": 0, "it": 0}
    for field, entry in FIELDS.items():
        if entry["en"].lower() == entry["it"].lower():
            continue
        found = _find_field(lines, field)
        if found is None:
            continue
        name = found[1].lower()
        for language in LANGUAGES:
            if name == entry[language].lower():
                votes[language] += 1
    return "it" if votes["it"] > votes["en"] else "en"


def _parse_date(text: str) -> dt.date | None:
    m = RE_DATE.search(text or "")
    if not m:
        return None
    try:
        return dt.date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
    except ValueError:
        return None


def _find_status_file(folder: Path) -> Path | None:
    """The right casing is CURRENT_STATUS.md, but variants are read all the same."""
    exact = folder / CANONICAL_NAME
    if exact.is_file():
        return exact
    try:
        for entry in sorted(folder.iterdir()):
            if entry.is_file() and entry.name.lower() == CANONICAL_NAME.lower():
                return entry
    except OSError:
        pass
    return None


def document(name: str, root_path: str, host_root: str) -> dict | None:
    """A project's status document, read again right now. None if there is none.

    `name` comes from the URL, so it is a label and not a path: it has to
    resolve to a DIRECT CHILD folder of root_path. That is checked after
    resolve(), not on the string, so a symlink pointing outside falls too.
    """
    if not name or "/" in name or "\\" in name or name.startswith("."):
        return None
    root = Path(root_path).resolve()
    try:
        folder = (root / name).resolve()
    except OSError:
        return None
    if folder.parent != root or not folder.is_dir():
        return None

    path = _find_status_file(folder)
    if path is None:
        return None
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
        mtime = dt.datetime.fromtimestamp(path.stat().st_mtime)
    except OSError:
        return None
    return {
        "name": folder.name,
        "text": text,
        "file": path.name,
        "host_path": host_join(host_root, folder.name, path.name),
        "mtime": mtime,
        "lines": text.count("\n") + 1,
    }


def host_join(base: str, *parts: str) -> str:
    """Join a path in the shape of the BASE, not of this machine.

    ⚠️ Not `os.path.join` and not `Path`: both answer for the machine running
    the code, and in a container the host path belongs to somebody else's — it
    may be Windows while this runs on Linux. Both joins already handle a base
    ending in a separator, `/` included.
    """
    flavour = ntpath if ntpath.splitdrive(base)[0] or "\\" in base else posixpath
    return flavour.join(base, *parts)


